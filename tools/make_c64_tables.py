#!/usr/bin/env python3
"""C64 tables from the MZ ones (docs/port-c64.md).

The C64's text mode is the MZ-700's: 40 x 25 cells of 8 x 8 pixels, one
colour a cell (colour RAM) on a common background (black, as every MZ cell
of the game and the title has). So the MZ characters are used as they are:
one 256-character set holds the glyphs of both the game's and the title's
tables, and each logical code becomes a screen code and a colour.

Tables written to c/platform/c64/tables.[ch]:
  c64_font          256 x 8 bytes: the character set (bit 7 leftmost)
  c64_game_code     logical code (game) -> screen code
  c64_game_colour   logical code (game) -> colour (0-15); the players' own
                    codes in the players' C64 colours
  c64_title_code    logical code (title mode) -> screen code
  c64_title_colour  logical code (title mode) -> colour
"""
import os, re

here = os.path.dirname(os.path.abspath(__file__))
CGROM = os.environ.get('MZ_CGROM', os.path.expanduser('~/src/mz-catalog/tools/mzfont/cgrom.bin'))
cg = open(CGROM, 'rb').read()
src = open(os.path.join(here, '..', 'c', 'platform', 'mz', 'tables.c')).read()

# the MZ's eight inks (black, blue, red, magenta, green, cyan, yellow, white) as C64 colours
C64_INK = [0, 6, 2, 4, 5, 3, 7, 1]
# the players' own codes in the game (as tools/make_atari_tables.py has them):
# light green, orange, light blue, light red (plat_c64.c's player_colours):
# none of these is in the field, and they are far apart
PLAYER_COLOURS = [13, 8, 14, 10]


def player_of(code):
    for p, base in ((0, 0x8a), (1, 0xa0), (2, 0xa4), (3, 0xa8)):
        if base <= code <= base + 3 or base + 0x10 <= code <= base + 0x13: return p
    return None


def table(name):
    i = src.index(name + '[512] = {'); j = src.index('};', i)
    return [int(x, 0) for x in re.findall(r'0x[0-9a-fA-F]+', src[i:j])]


font, index = [bytes(8)], {bytes(8): 0}


def screen_code(display):
    g = bytes(int(f'{b:08b}'[::-1], 2) for b in cg[display * 8: display * 8 + 8])   # MZ: bit 0 leftmost
    if g not in index:
        index[g] = len(font); font.append(g)
    return index[g]


codes, colours = {}, {}
for name in ('game', 'title'):
    t = table(name + '_table')
    codes[name] = [screen_code(t[2 * c]) for c in range(256)]
    colours[name] = [C64_INK[(t[2 * c + 1] >> 4) & 7] for c in range(256)]
    if name == 'game':
        for c in range(256):
            if player_of(c) is not None: colours[name][c] = PLAYER_COLOURS[player_of(c)]
        for p, c in enumerate((0xae, 0xaf, 0xbc, 0xbd)):   # the status line's '1'..'4' (core/game.c: player_digit_codes)
            colours[name][c] = PLAYER_COLOURS[p]
assert len(font) <= 256, len(font)


def carray(name, data, per=16):
    lines = [f'const uint8_t {name}[{len(data)}] = {{']
    for i in range(0, len(data), per): lines.append('  ' + ', '.join(f'0x{b:02x}' for b in data[i:i + per]) + ',')
    return '\n'.join(lines + ['};', ''])


out = os.path.join(here, '..', 'c', 'platform', 'c64')
os.makedirs(out, exist_ok=True)
open(os.path.join(out, 'tables.c'), 'w').write('\n'.join([
    '/* Generated by tools/make_c64_tables.py from the MZ tables - do not edit. */',
    '#include <stdint.h>', '#include "tables.h"', '',
    carray('c64_font', b''.join(font) + bytes(8 * (256 - len(font)))),
    carray('c64_game_code', bytes(codes['game'])), carray('c64_game_colour', bytes(colours['game'])),
    carray('c64_title_code', bytes(codes['title'])), carray('c64_title_colour', bytes(colours['title']))]))
open(os.path.join(out, 'tables.h'), 'w').write(
    '/* Generated by tools/make_c64_tables.py - do not edit. */\n#ifndef TABLES_H\n#define TABLES_H\n#include <stdint.h>\n'
    'extern const uint8_t c64_font[2048];\n'
    'extern const uint8_t c64_game_code[256], c64_game_colour[256], c64_title_code[256], c64_title_colour[256];\n#endif\n')
print(f'character set: {len(font)} of 256 glyphs')
