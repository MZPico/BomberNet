#!/usr/bin/env python3
"""The game core on a 6502: built with llvm-mos for its simulator (mos-sim),
replaying a recording with the state hash checked every game frame, the
frames' work counted in CPU cycles (c/platform/sim6502).

  tools/sim6502.py tests/recordings/dm4.bnr [-O2|-Os|...] [--hash-off] [--profile]

LLVM_MOS: the SDK (default ~/src/llvm-mos-dl/llvm-mos). --hash-off times a
standalone game (no hash, so nothing is checked). --profile lists the
functions by cycles (mos-sim --profile, mapped through llvm-nm).
Budget per 60 ms frame: 90,000 cycles on an Atari XL/XE in a text mode
(about 1.5 MHz left of 1.77 after ANTIC's DMA), 56,400 on a C64 (0.94 MHz)."""
import os, re, subprocess, sys, collections

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
SDK = os.environ.get('LLVM_MOS', os.path.expanduser('~/src/llvm-mos-dl/llvm-mos'))
args = [a for a in sys.argv[1:] if not a.startswith('-')]
opts = [a for a in sys.argv[1:] if a.startswith('-O')] or ['-O2']
rec = args[0]
out = os.path.join(ROOT, 'build', 'sim6502'); os.makedirs(out, exist_ok=True)
data = open(rec, 'rb').read()
with open(os.path.join(out, 'rec_data.h'), 'w') as f:
    f.write(f'/* {os.path.basename(rec)} - generated by tools/sim6502.py */\n#define REC_LEN {len(data)}u\n'
            'static const uint8_t rec[REC_LEN] = {\n')
    for i in range(0, len(data), 24): f.write('  ' + ', '.join(str(b) for b in data[i:i + 24]) + ',\n')
    f.write('};\n')
c = os.path.join(ROOT, 'c')
src = [f'{c}/core/{n}.c' for n in ('bomber', 'netplay', 'data', 'map', 'game', 'input', 'video', 'enemy', 'bomb', 'player')]
src += [f'{c}/platform/mz/tables.c', f'{c}/common/netdev_none.c', f'{c}/platform/sim6502/plat_sim6502.c']
inc = [f'-I{c}/core', f'-I{c}/common', f'-I{c}/platform/sim6502', f'-I{c}/platform/mz', f'-I{out}']
elf = os.path.join(out, 'bomber.elf'); binf = os.path.join(out, 'bomber')
flags = opts + (['-DHASH_OFF'] if '--hash-off' in sys.argv else []) + os.environ.get('CFLAGS6502', '').split()
r = subprocess.run([f'{SDK}/bin/mos-sim-clang', *flags, *inc, *src, '-o', binf, '-Wl,--gc-sections'], capture_output=True, text=True)
if r.returncode: sys.exit(r.stderr[-3000:])
size = os.path.getsize(binf)
prof = '--profile' in sys.argv
r = subprocess.run([f'{SDK}/bin/mos-sim', *(['--profile'] if prof else []), binf], capture_output=True, text=True, timeout=3600)
o = r.stdout
print(f'{os.path.basename(rec)} {" ".join(flags)}: program {size} bytes')
for l in o.splitlines():
    if l.startswith(('RESULT', 'CYCLES', 'OVER', 'MISMATCH')): print(' ', l)
m = re.search(r'CYCLES median (\d+) p90 (\d+) p99 (\d+) max (\d+)', o)
if m:
    med, p90, p99, mx = map(int, m.groups())
    for name, hz in (('Atari XL/XE (~1.5 MHz)', 1.5e6), ('C64 (0.94 MHz)', 0.94e6)):
        print(f'  {name}: median {med / hz * 1000:.1f} ms, p90 {p90 / hz * 1000:.1f}, p99 {p99 / hz * 1000:.1f}, max {mx / hz * 1000:.0f}')
if prof:
    syms = []
    for l in subprocess.run([f'{SDK}/bin/llvm-nm', '-n', elf if os.path.exists(elf) else binf + '.elf'], capture_output=True, text=True).stdout.splitlines():
        p = l.split()
        if len(p) == 3 and p[1] in 'tTW': syms.append((int(p[0], 16), p[2]))
    import bisect
    addrs = [a for a, _ in syms]; acc = collections.Counter()
    for l in r.stderr.splitlines():
        p = l.split()
        if len(p) == 2 and re.fullmatch(r'[0-9a-fA-F]+', p[0]) and p[1].isdigit():
            a = int(p[0], 16); i = bisect.bisect_right(addrs, a) - 1
            if i >= 0: acc[syms[i][1]] += int(p[1])
    gf = int(re.search(r'RESULT frames (\d+)', o).group(1))
    for n, v in acc.most_common(25): print(f'   {n:28} {v / gf:8.0f} cycles per game frame')
