#!/usr/bin/env python3
"""The 128K Spectrum's bank 6 module: its entry points for the game.

  tools/zx128_entries.py bank6.map bank6_entries.h

Reads the addresses of the functions the game calls (c/platform/zx/
tcp_bank6.c) from the map of the module linked at C000h, writes them as
#defines, and checks that the module ends below its stack (the top 512
bytes of the bank)."""
import re, sys

ENTRIES = {'BANK6_SIGNATURE': '_bank6_signature', 'BANK6_INIT': '_bank6_init',
           'BANK6_TCP_PRESENT': '_tcp_present', 'BANK6_TCP_OPEN': '_tcp_open',
           'BANK6_TCP_SEND': '_tcp_send', 'BANK6_TCP_RECV': '_tcp_recv', 'BANK6_TCP_CLOSE': '_tcp_close'}
STACK = 0xfe00

mapf, out = sys.argv[1], sys.argv[2]
syms = {n: int(v, 16) for n, v in re.findall(r'^(\S+)\s+= \$([0-9A-Fa-f]+)', open(mapf).read(), re.M)}
end = syms['__BSS_END_tail']
if end > STACK:
    sys.exit(f'bank 6: the module ends at {end:04X}h, over its stack from {STACK:04X}h')
lines = ['/* Generated by tools/zx128_entries.py from the bank 6 map - do not edit. */']
lines += [f'#define {k} 0x{syms[v]:04x}' for k, v in ENTRIES.items()]
open(out, 'w').write('\n'.join(lines) + '\n')
print(f'bank 6: {end - 0xc000} bytes used, {STACK - end} free below the stack')
