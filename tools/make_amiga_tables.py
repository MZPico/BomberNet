#!/usr/bin/env python3
"""Amiga tables from the MZ ones (docs/port-amiga.md).

The screen is a bitmap of 4 bitplanes (16 colours): a cell is the MZ's
8 x 8 glyph in one colour, so the MZ character ROM is used as it is, and
each logical code becomes a glyph number and a colour. One glyph table
serves the game's and the title's codes.

Tables written to c/platform/amiga/tables.[ch]:
  amiga_glyphs        8 bytes a glyph, bit 7 the leftmost pixel
  amiga_game_glyph    logical code (game) -> glyph number
  amiga_game_colour   logical code (game) -> colour (0-15); the players'
                      own codes and their status-line digits in the players' colours
  amiga_title_glyph   logical code (title mode) -> glyph number
  amiga_title_colour  logical code (title mode) -> colour
  amiga_palette       16 colours as the Amiga's 12-bit RGB words
"""
import os, re

here = os.path.dirname(os.path.abspath(__file__))
CGROM = os.environ.get('MZ_CGROM', os.path.expanduser('~/src/mz-catalog/tools/mzfont/cgrom.bin'))
cg = open(CGROM, 'rb').read()
src = open(os.path.join(here, '..', 'c', 'platform', 'mz', 'tables.c')).read()

# the palette: the MZ's eight inks (black, blue, red, magenta, green, cyan,
# yellow, white) in 0-7, the four players' own colours in 8-11 (light green,
# orange, light blue, light red: in the field only on the players), spares
PALETTE = [0x000, 0x44F, 0xF22, 0xF2F, 0x2E2, 0x3EF, 0xFE2, 0xFFF,
           0x9F8, 0xF93, 0x9CF, 0xF99, 0x888, 0xCCC, 0x642, 0x060]
PLAYER_COLOURS = [8, 9, 10, 11]


def player_of(code):
    for p, base in ((0, 0x8a), (1, 0xa0), (2, 0xa4), (3, 0xa8)):
        if base <= code <= base + 3 or base + 0x10 <= code <= base + 0x13: return p
    return None


def table(name):
    i = src.index(name + '[512] = {'); j = src.index('};', i)
    return [int(x, 0) for x in re.findall(r'0x[0-9a-fA-F]+', src[i:j])]


glyphs, index = [bytes(8)], {bytes(8): 0}


def glyph_number(display):
    g = bytes(int(f'{b:08b}'[::-1], 2) for b in cg[display * 8: display * 8 + 8])   # MZ: bit 0 leftmost
    if g not in index:
        index[g] = len(glyphs); glyphs.append(g)
    return index[g]


numbers, colours = {}, {}
for name in ('game', 'title'):
    t = table(name + '_table')
    numbers[name] = [glyph_number(t[2 * c]) for c in range(256)]
    colours[name] = [(t[2 * c + 1] >> 4) & 7 for c in range(256)]
    if name == 'game':
        for c in range(256):
            if player_of(c) is not None: colours[name][c] = PLAYER_COLOURS[player_of(c)]
        for p, c in enumerate((0xae, 0xaf, 0xbc, 0xbd)):   # the status line's '1'..'4' (core/game.c: player_digit_codes)
            colours[name][c] = PLAYER_COLOURS[p]


def carray(ctype, name, data, per=16):
    fmt = '0x%03x' if ctype == 'uint16_t' else '0x%02x'
    lines = [f'const {ctype} {name}[{len(data)}] = {{']
    for i in range(0, len(data), per): lines.append('  ' + ', '.join(fmt % b for b in data[i:i + per]) + ',')
    return '\n'.join(lines + ['};', ''])


out = os.path.join(here, '..', 'c', 'platform', 'amiga')
os.makedirs(out, exist_ok=True)
open(os.path.join(out, 'tables.c'), 'w').write('\n'.join([
    '/* Generated by tools/make_amiga_tables.py from the MZ tables - do not edit. */',
    '#include <stdint.h>', '#include "tables.h"', '',
    carray('uint8_t', 'amiga_glyphs', b''.join(glyphs), 8),
    carray('uint8_t', 'amiga_game_glyph', bytes(numbers['game'])), carray('uint8_t', 'amiga_game_colour', bytes(colours['game'])),
    carray('uint8_t', 'amiga_title_glyph', bytes(numbers['title'])), carray('uint8_t', 'amiga_title_colour', bytes(colours['title'])),
    carray('uint16_t', 'amiga_palette', PALETTE)]))
open(os.path.join(out, 'tables.h'), 'w').write(
    '/* Generated by tools/make_amiga_tables.py - do not edit. */\n#ifndef TABLES_H\n#define TABLES_H\n#include <stdint.h>\n'
    f'extern const uint8_t amiga_glyphs[{8 * len(glyphs)}];\n'
    'extern const uint8_t amiga_game_glyph[256], amiga_game_colour[256], amiga_title_glyph[256], amiga_title_colour[256];\n'
    'extern const uint16_t amiga_palette[16];\n#endif\n')
print(f'{len(glyphs)} glyphs')
